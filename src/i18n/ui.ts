export function floorName(i: number, lang: Lang) {
  if (lang === "hi")
    return (
      [
        "ग्राउंड फ़्लोर",
        "पहली मंज़िल",
        "दूसरी मंज़िल",
        "तीसरी मंज़िल",
        "चौथी मंज़िल",
      ].at(i) ?? `${i} मंज़िल`
    );
  if (i === 0) return "Ground floor";
  const suffix = i === 1 ? "st" : i === 2 ? "nd" : i === 3 ? "rd" : "th";
  return `${i}${suffix} floor`;
}
